/// Reports, the prototype's third tab, from archive/prototype-google-ai-studio/src/components/ReportsScreen.tsx.
///
/// Every figure comes out of core/money/reports.dart, which is locked to
/// vectors generated by running the prototype's own arithmetic. This file
/// decides what the screen LOOKS like and nothing about what it says.
///
/// SCOPE, named rather than implied. The prototype's Reports has a fourth
/// tab, Reconciliation, which is the only one that WRITES: it creates an
/// adjustment transaction to force the app's balance to match a real bank
/// balance, and it changes a transaction's status. A write path needs both
/// halves tested (the money, and a journey that taps to every screen which
/// should mention it afterwards), so it is its own batch rather than a fourth
/// tab bolted onto three read-only ones. The tab bar says so on screen rather
/// than leaving a gap somebody has to guess about.
///
/// Also not ported with it: CSV export (nothing in app/ can write a file yet)
/// and the comparison toggle (previous period, budget, forecast), which needs
/// period-over-period history the app does not keep.
class ReportsScreen extends StatefulWidget {
  const ReportsScreen({super.key, required this.state});

  final FinancialState state;

  @override
  State<ReportsScreen> createState() => _ReportsScreenState();
}

enum _ReportTab { position, performance, cashFlow, reconciliation }

/// Money with an explicit minus sign when it is negative.
///
/// [formatPeso] deliberately returns the ABSOLUTE value, because on most
/// screens the sign is carried by a label ("Money out") or an arrow. On this
/// screen it is not: net worth, net cash change and every "Net" row can land
/// on either side of zero, and without this a debt of 217,229.50 renders
/// character for character like savings of 217,229.50.
///
/// Colour alone cannot carry it. Roughly one man in twelve cannot reliably
/// separate the red from the green, and a screenshot, a printout or a
/// greyscale screen loses it for everybody.
/// Was a private copy of what is now formatPesoWithSign in format.dart. Pan
/// lacked the same line and reported a negative net worth as a positive
/// figure, so the two screens disagreed about a sign over one store.
String _signed(double v) => formatPesoWithSign(v);

/// "8 accounts" became a lie on 2026-10-05 and this is what replaced it.
///
/// The two totals it captions are no longer built from accounts alone: debts
/// entered on the Debt screen and instalment plans are in them too. A caption
/// that counts a different population from the figure above it is worse than
/// no caption, because somebody will divide one by the other and get an
/// average that is of nothing.
String _sources(int n) => n == 1 ? '1 entry' : '$n entries';

/// A ratio, or a dash when there is nothing to take a ratio OF.
///
/// Both published ratios return 0 when income is zero or negative
/// (`reports.dart:641` and `:643`). That is correct arithmetic and a terrible
/// reading: pick "This week" in the days before payday, which is exactly when
/// a worried person opens this tab, and the screen reports a savings rate of
/// 0.0% and debt servicing of 0.0% over a week that may hold thousands in loan
/// payments and no pay at all.
///
/// 0.0% is a measurement. The truth is that there is no measurement. A dash
/// says so and cannot be misread as a result.
///
/// The figure passed in is EARNED income, not "Money in", and the difference
/// is the whole point. Both ratios divide by what was earned, so a period
/// whose only inflow was a repayment has money in above zero and nothing to
/// divide by. Asking `totalIncome > 0` here let that case through and printed
/// the engine's "no measurement" zero as "0.0%", which is exactly what this
/// function exists to prevent.
String _ratioText(double ratio, double earnedIncome) =>
    earnedIncome > 0 ? '${ratio.toStringAsFixed(1)}%' : '-';

class _ReportsScreenState extends State<ReportsScreen> {
  _ReportTab _tab = _ReportTab.position;
  ReportPeriod _period = ReportPeriod.monthly;

  @override
  Widget build(BuildContext context) {
    final Palette p = Palette.of(widget.state.theme);

    // ONE call, so the three tabs cannot disagree about which entries they
    // were looking at. The profile comes from the shared store rather than a
    // local field, so switching entity on Activity and coming here does not
    // silently show a different scope.
    final ReportSet r = buildReports(
      transactions: widget.state.transactions,
      accounts: widget.state.accounts,
      period: _period,
      now: widget.state.now,
      profile: widget.state.activeProfile,
      // What a person entered on the Debt and Plans screens is money they
      // owe, and until 2026-10-05 the balance sheet could not see it. A
      // figure that changes depending on WHICH SCREEN a debt was typed into
      // is not a balance sheet.
      debts: widget.state.debts,
      plans: widget.state.installments,
    );

    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: <Widget>[
        _Header(palette: p, profile: widget.state.activeProfile),
        _TabBar(
          palette: p,
          current: _tab,
          onSelect: (_ReportTab t) => setState(() => _tab = t),
        ),
        Expanded(
          child: ListView(
            padding: const EdgeInsets.fromLTRB(
              Spacing.lg,
              Spacing.md,
              Spacing.lg,
              Spacing.xl,
            ),
            children: <Widget>[
              // The period picker is hidden on Position, deliberately. A
              // balance sheet is what you own NOW; offering "this week" beside
              // it would imply the app can show last week's net worth, which
              // needs history it does not keep.
              if (_tab != _ReportTab.position &&
                  _tab != _ReportTab.reconciliation) ...<Widget>[
                _PeriodPicker(
                  palette: p,
                  current: _period,
                  onSelect: (ReportPeriod v) => setState(() => _period = v),
                ),
                const SizedBox(height: Spacing.md),
                _ScopeNote(palette: p, count: r.transactions.length),
                const SizedBox(height: Spacing.lg),
              ],
              switch (_tab) {
                _ReportTab.position => _PositionView(palette: p, report: r),
                _ReportTab.performance => _PerformanceView(
                  palette: p,
                  report: r,
                  period: _period,
                ),
                _ReportTab.cashFlow => _CashFlowView(palette: p, report: r),
                _ReportTab.reconciliation => ReconciliationView(
                  state: widget.state,
                ),
              },
              if (_tab != _ReportTab.reconciliation) ...<Widget>[
                const SizedBox(height: Spacing.lg),
                _ReconciliationNote(palette: p),
              ],
            ],
          ),
        ),
      ],
    );
  }
}

