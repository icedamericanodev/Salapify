class _FlowSection extends StatelessWidget {
  const _FlowSection({
    required this.palette,
    required this.title,
    required this.note,
    required this.inflows,
    required this.outflows,
    required this.net,
  });

  final Palette palette;
  final String title;
  final String note;
  final double inflows;
  final double outflows;
  final double net;

  @override
  Widget build(BuildContext context) {
    final bool empty = inflows == 0 && outflows == 0;

    // Zero is neither good nor bad. Painting ₱0.00 green reads as a small
    // win and orange reads as a small loss, and it is neither: it means
    // nothing of this kind happened.
    Color colourFor(double v, Color whenNonZero) =>
        v == 0 ? palette.textMuted : whenNonZero;

    return _SectionCard(
      palette: palette,
      title: title,
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: <Widget>[
          BreakdownRow(
            palette: palette,
            label: 'In',
            value: formatPeso(inflows),
            valueColor: colourFor(inflows, palette.positive),
          ),
          BreakdownRow(
            palette: palette,
            label: 'Out',
            value: formatPeso(outflows),
            valueColor: colourFor(outflows, palette.negative),
          ),
          Divider(color: palette.border, height: Spacing.lg),
          BreakdownRow(
            palette: palette,
            label: 'Net',
            value: _signed(net),
            emphasis: true,
            valueColor: colourFor(
              net,
              net >= 0 ? palette.positive : palette.negative,
            ),
          ),
          const SizedBox(height: 2),
          Text(
            // Three zeros with no comment invite the reading that the section
            // is broken, so the empty case still says so. It is four words
            // rather than a sentence.
            empty ? '$note. None this period.' : note,
            style: AppType.caption(palette),
          ),
        ],
      ),
    );
  }
}

