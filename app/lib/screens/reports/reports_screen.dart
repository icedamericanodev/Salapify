class _TabBar extends StatelessWidget {
  const _TabBar({
    required this.palette,
    required this.current,
    required this.onSelect,
  });

  final Palette palette;
  final _ReportTab current;
  final ValueChanged<_ReportTab> onSelect;

  static const Map<_ReportTab, String> _labels = <_ReportTab, String>{
    _ReportTab.position: 'Position',
    _ReportTab.performance: 'Performance',
    _ReportTab.cashFlow: 'Cash flow',
    _ReportTab.reconciliation: 'Check',
  };

  @override
  Widget build(BuildContext context) {
    return Container(
      decoration: BoxDecoration(
        border: Border(bottom: BorderSide(color: palette.border)),
      ),
      child: Row(
        children: <Widget>[
          for (final MapEntry<_ReportTab, String> e in _labels.entries)
            Expanded(
              child: Semantics(
                selected: current == e.key,
                button: true,
                child: InkWell(
                  onTap: () => onSelect(e.key),
                  child: Container(
                    // 44 logical pixels is the floor for anything tappable.
                    constraints: const BoxConstraints(minHeight: 44),
                    alignment: Alignment.center,
                    decoration: BoxDecoration(
                      border: Border(
                        bottom: BorderSide(
                          color: current == e.key
                              ? palette.accent
                              : Colors.transparent,
                          width: 2,
                        ),
                      ),
                    ),
                    // A CAP, and a small one, for the same reason the tab bar
                    // has one: four segments share the width of the phone and
                    // the longest of them is a single eleven letter word, so
                    // at 1.5x "Performance" was cut to "Performa...".
                    //
                    // Two lines was tried first and was worse. "Performance"
                    // has no space in it, so there is no line break
                    // opportunity inside it, and Flutter fell back to
                    // breaking between characters: the segment read
                    // "Performa" over "nce", which looks like a rendering
                    // fault rather than a label.
                    //
                    // 1.1 is measured, not chosen. "Performance" needs 85.9dp
                    // and a quarter of a 390dp phone gives it 97.5, so 1.13
                    // is the ceiling and 1.1 is the round number under it.
                    // That is barely any growth and it is said plainly rather
                    // than dressed up: the honest gain here is that the whole
                    // word survives at every font size, not that it gets
                    // bigger. Growing this properly means a scrolling
                    // segmented control or a shorter word, both of which
                    // change the product rather than fix a defect.
                    child: MediaQuery.withClampedTextScaling(
                      maxScaleFactor: 1.1,
                      child: Text(
                        e.value,
                        maxLines: 1,
                        textAlign: TextAlign.center,
                        overflow: TextOverflow.ellipsis,
                        style: AppType.button(
                          palette,
                          color: current == e.key
                              ? palette.accent
                              : palette.textMuted,
                        ),
                      ),
                    ),
                  ),
                ),
              ),
            ),
        ],
      ),
    );
  }
}

class _PeriodPicker extends StatelessWidget {
  const _PeriodPicker({
    required this.palette,
    required this.current,
    required this.onSelect,
  });

  final Palette palette;
  final ReportPeriod current;
  final ValueChanged<ReportPeriod> onSelect;

  @override
  Widget build(BuildContext context) {
    // Wrap rather than a Row: six labels do not fit one line on a 320dp phone,
    // and a horizontal scroller hides the options somebody is looking for.
    return Wrap(
      spacing: Spacing.xs,
      runSpacing: Spacing.xs,
      children: <Widget>[
        for (final ReportPeriod p in ReportPeriod.values)
          Semantics(
            selected: p == current,
            button: true,
            child: InkWell(
              onTap: () => onSelect(p),
              borderRadius: BorderRadius.circular(Radii.pill),
              // NO `alignment:` on this Container, and that is the whole
              // reason it is written this way. A Container given an alignment
              // and no width expands to its maximum constraint, so each pill
              // filled the row and the six of them stacked into a column that
              // ate a third of the screen. A Row with mainAxisSize.min sizes
              // to its content and still centres vertically, which is the
              // pattern the Log pill in the shell already uses.
              child: Container(
                constraints: const BoxConstraints(minHeight: 44),
                padding: const EdgeInsets.symmetric(horizontal: Spacing.md),
                decoration: BoxDecoration(
                  color: p == current ? palette.accent : palette.card,
                  borderRadius: BorderRadius.circular(Radii.pill),
                  border: Border.all(
                    color: p == current ? palette.accent : palette.border,
                  ),
                ),
                child: Row(
                  mainAxisSize: MainAxisSize.min,
                  children: <Widget>[
                    Text(
                      p.label,
                      style: AppType.button(
                        palette,
                        color: p == current
                            ? palette.onAccent
                            : palette.textSecondary,
                      ),
                    ),
                  ],
                ),
              ),
            ),
          ),
      ],
    );
  }
}

/// Says how many entries the figures below were computed from.
///
/// This is not decoration. Every total on this screen is a sum over a set the
/// person cannot see, and "0 entries" is the difference between "I earned
/// nothing this week" and "the filter is wrong".
class _ScopeNote extends StatelessWidget {
  const _ScopeNote({required this.palette, required this.count});

  final Palette palette;
  final int count;

  @override
  Widget build(BuildContext context) {
    final String entries = count == 1 ? '1 entry' : '$count entries';
    return Row(
      children: <Widget>[
        Expanded(
          child: Text(
            // The zero case keeps its reassurance, because an empty report is
            // the state most likely to be read as a broken one. The normal
            // case is now three words instead of a sentence about excluded
            // entries, which is in the explainer.
            count == 0
                ? 'No entries in this period, so nothing to report yet.'
                : 'From $entries',
            style: AppType.caption(palette),
          ),
        ),
        InfoDot(
          color: palette.textMuted,
          semanticLabel: 'What is being counted',
          onTap: () => InfoSheet.show(context, palette, InfoTopic.reportScope),
        ),
      ],
    );
  }
}

class _PositionView extends StatelessWidget {
  const _PositionView({required this.palette, required this.report});

  final Palette palette;
  final ReportSet report;

  @override
  Widget build(BuildContext context) {
    final FinancialPosition p = report.position;
    final bool underwater = p.netWorth.centavos < 0;
    final bool hasMortgage = p.liabilityAccounts.any(
      (Account a) => a.kind == AccountKind.mortgage,
    );
    // Whether the gap the sentence below describes is still a gap. It stopped
    // being one on 2026-10-05 for anybody who records the home itself.
    final bool hasProperty = p.assetAccounts.any(
      (Account a) => a.kind == AccountKind.property,
    );

    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: <Widget>[
        // ABOVE THE FIGURE, NOT BESIDE IT, and the placement is the whole
        // design. A user panel found that a caveat sitting NEXT TO a headline
        // made one archetype distrust the headline itself. Above it, with the
        // reassurance in the same breath, says "read this first, then read
        // the number" instead of "this number is suspect".
        //
        // Nothing renders at all when the books are clean. No green tick, no
        // "all balanced" badge: a permanent reassurance nobody asked for
        // teaches people to read this whole area as decoration, which is
        // exactly what the 2026-09-18 rule rules out.
        if (report.duplicateBalances.isNotEmpty) ...<Widget>[
          _DoubleCountCard(palette: palette, flags: report.duplicateBalances),
          const SizedBox(height: Spacing.md),
        ],
        _SectionCard(
          palette: palette,
          // NOT "Net worth" WHEN IT IS NEGATIVE, on founder decision of
          // 2026-10-05. The arithmetic is unchanged and the figure is the
          // same figure; only the name moves.
          //
          // "Net worth: minus 217,229" is a verdict on a person. "Still to
          // pay off: 217,229" is a job with a finish line, and it is the
          // identical number read from the other end. For the audience this
          // app is for, a deeply negative figure is normal: it is usually one
          // mortgage, taken out deliberately, on a 25 year instrument
          // designed to be largest at the start. A headline that reads as a
          // judgement on a decision somebody already made, and cannot revisit
          // this fortnight, is a number they learn to stop opening.
          //
          // The word "net worth" is not hidden. It is the first line behind
          // the dot, because somebody who meets it at a bank or on a loan
          // form should recognise it.
          title: underwater ? 'Still to pay off' : 'What is really yours',
          topic: InfoTopic.netWorth,
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: <Widget>[
              FittedBox(
                fit: BoxFit.scaleDown,
                alignment: Alignment.centerLeft,
                child: Text(
                  // UNSIGNED when underwater, because the minus sign is doing
                  // the work the old title did. "Still to pay off, minus
                  // 217,229" would read as a negative amount of debt.
                  underwater
                      ? formatPeso(p.netWorth.abs.pesos)
                      : _signed(p.netWorth.pesos),
                  style: AppType.hero(palette).copyWith(
                    color: underwater ? palette.negative : palette.positive,
                  ),
                ),
              ),
              // A = L + E, in the only words that need no glossary, and on
              // the screen rather than behind the dot because it is two
              // figures rather than a lesson. It is also what makes the
              // headline checkable: a person can see where it came from
              // without being told what an identity is.
              const SizedBox(height: 2),
              Text(
                'You own ${formatPeso(p.totalAssets.pesos)} and owe '
                '${formatPeso(p.totalLiabilities.pesos)}.',
                style: AppType.caption(palette),
              ),
              // THE WRONG CONCLUSION STOPPER, and it is now specific rather
              // than reassuring. It used to read "A housing loan alone can do
              // this", which excuses the figure without explaining it.
              //
              // The real reason was a modelling gap: `AccountKind` had no kind
              // for a thing you own outright, so a mortgage entered the ledger
              // with no house on the other side and the figure was not merely
              // unflattering, it was incomplete.
              //
              // THAT GAP IS CLOSEABLE NOW, which is why the sentence is gated
              // on more than a mortgage. Somebody who has recorded the home
              // itself IS having it counted, and telling them otherwise would
              // be the app printing a false statement to the one person who
              // did the thing it asked for. The condition reads "a mortgage
              // and no property", not "a mortgage".
              //
              // The other branch covers somebody underwater on cards alone,
              // who would otherwise be told about a home they do not have.
              if (underwater) ...<Widget>[
                const SizedBox(height: 2),
                Text(
                  hasMortgage && !hasProperty
                      ? 'Your home is not counted here, only the loan on it. '
                            'Add it under Accounts and this balances out.'
                      : 'This counts what you owe in full, including debts '
                            'you are paying down.',
                  style: AppType.caption(palette),
                ),
              ],
            ],
          ),
        ),
        const SizedBox(height: Spacing.md),
        StatPair(
          left: StatCard(
            palette: palette,
            label: 'Assets',
            value: formatPeso(p.totalAssets.pesos),
            caption: _sources(p.assetSourceCount),
            valueColor: palette.positive,
          ),
          right: StatCard(
            palette: palette,
            label: 'Liabilities',
            value: formatPeso(p.totalLiabilities.pesos),
            caption: _sources(p.liabilitySourceCount),
            valueColor: palette.negative,
          ),
        ),
        const SizedBox(height: Spacing.md),
        _SectionCard(
          palette: palette,
          title: 'What you own',
          child: Column(
            children: <Widget>[
              BreakdownRow(
                palette: palette,
                label: 'Cash and e-wallets',
                value: formatPeso(p.cashEquivalents.pesos),
              ),
              BreakdownRow(
                palette: palette,
                label: 'Investments',
                value: formatPeso(p.investments.pesos),
              ),
              BreakdownRow(
                palette: palette,
                label: 'Owed to you',
                value: formatPeso(p.receivables.pesos),
              ),
              Divider(color: palette.border, height: Spacing.lg),
              BreakdownRow(
                palette: palette,
                label: 'Total assets',
                value: formatPeso(p.totalAssets.pesos),
                emphasis: true,
                valueColor: palette.positive,
              ),
            ],
          ),
        ),
        const SizedBox(height: Spacing.md),
        _SectionCard(
          palette: palette,
          title: 'What you owe',
          child: Column(
            children: <Widget>[
              BreakdownRow(
                palette: palette,
                label: 'Credit cards',
                value: formatPeso(p.creditCards.pesos),
              ),
              BreakdownRow(
                palette: palette,
                label: 'Loans and mortgage',
                value: formatPeso(p.loans.pesos),
              ),
              Divider(color: palette.border, height: Spacing.lg),
              BreakdownRow(
                palette: palette,
                label: 'Total liabilities',
                value: formatPeso(p.totalLiabilities.pesos),
                emphasis: true,
                valueColor: palette.negative,
              ),
            ],
          ),
        ),
      ],
    );
  }
}

class _PerformanceView extends StatefulWidget {
  const _PerformanceView({
    required this.palette,
    required this.report,
    required this.period,
  });

  final Palette palette;
  final ReportSet report;
  final ReportPeriod period;

  @override
  State<_PerformanceView> createState() => _PerformanceViewState();
}

class _PerformanceViewState extends State<_PerformanceView> {
  /// Whether the breakdown below is narrowed to claimable receipts.
  ///
  /// Off every time the tab is built, deliberately. A filter that survives
  /// out of sight is how somebody comes back tomorrow, reads "Where it went"
  /// as their whole month, and is short by everything that was not a
  /// business expense. The heading changes with it for the same reason.
  bool _claimableOnly = false;

  @override
  Widget build(BuildContext context) {
    final Palette palette = widget.palette;
    final ReportSet report = widget.report;
    final ReportPeriod period = widget.period;
    final FinancialPerformance f = report.performance;
    final bool positive = f.netSurplus >= 0;

    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: <Widget>[
        StatPair(
          left: StatCard(
            palette: palette,
            label: 'Money in',
            value: formatPeso(f.totalIncome),
            valueColor: palette.positive,
          ),
          right: StatCard(
            palette: palette,
            label: 'Money out',
            value: formatPeso(f.totalExpenses),
            valueColor: palette.negative,
          ),
        ),
        // MONEY THAT CAME BACK IS NOT MONEY EARNED, said once, under the
        // figure it qualifies.
        //
        // A repayment collected from somebody who owed you arrives as income
        // in the ledger, so "Money in" counts it, correctly: it really did
        // arrive. It is not earnings though, it is an asset turning back into
        // cash, and the balance sheet already treats it that way. Both
        // published ratios now divide by what was EARNED, so without this
        // line the two figures would silently disagree about one peso.
        if (f.repaymentInflows > 0) ...<Widget>[
          const SizedBox(height: Spacing.xs),
          Text(
            '${formatPeso(f.repaymentInflows)} of this is money coming back '
            'to you, not new money. The rates below leave it out.',
            style: AppType.caption(palette),
          ),
        ],
        const SizedBox(height: Spacing.md),
        _SectionCard(
          palette: palette,
          title: positive ? 'You kept' : 'You overspent by',
          // InfoTopic.performance WAS DEFINED AND UNREACHABLE. No screen
          // opened it, so three explanations (what counts as money in, what
          // counts as money out, and why an excluded entry reaches neither)
          // existed and could not be read by anybody.
          //
          // This card is where they belong rather than a tidy place to park
          // them: the topic's own formula is "Kept = money in - money out",
          // which is this card's hero figure. Hanging it off the Money in and
          // Money out pair instead would have meant inventing a title for the
          // one block on the tab that does not need one.
          //
          // Content nobody can reach cannot be reviewed, and quietly rots.
          // That is how the explainer behind the ratios card came to teach a
          // pass mark the screen had already removed.
          topic: InfoTopic.performance,
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: <Widget>[
              FittedBox(
                fit: BoxFit.scaleDown,
                alignment: Alignment.centerLeft,
                child: Text(
                  formatPeso(f.netSurplus.abs()),
                  style: AppType.hero(palette).copyWith(
                    color: positive ? palette.positive : palette.negative,
                  ),
                ),
              ),
              const SizedBox(height: Spacing.xs),
              Text(
                // `keptRate`, not `savingsRate`. This card is about the cash
                // left over, and the savings rate now counts money moved into
                // an investment as saved, so the two are different numbers
                // and using the wrong one here would make the card contradict
                // its own hero figure.
                positive
                    ? 'That is ${f.keptRate.toStringAsFixed(1)}% of what '
                          'came in.'
                    : 'More went out than came in over this period.',
                style: AppType.caption(palette),
              ),
              // WHERE THE REST WENT, when some of it went somewhere rather
              // than simply out. A figure, not a lesson, so it belongs on the
              // screen: without it a person who put money into MP2 reads a
              // small "kept" figure and concludes they saved nothing.
              if (f.investedOutflows > 0) ...<Widget>[
                const SizedBox(height: Spacing.xs),
                Text(
                  '${formatPeso(f.investedOutflows)} of what went out went '
                  'into investments.',
                  style: AppType.caption(palette),
                ),
              ],
            ],
          ),
        ),
        const SizedBox(height: Spacing.md),
        _SectionCard(
          palette: palette,
          title: 'Two ratios worth watching',
          topic: InfoTopic.ratios,
          child: Column(
            children: <Widget>[
